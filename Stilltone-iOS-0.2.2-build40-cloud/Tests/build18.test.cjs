const assert = require('node:assert/strict');
const fs=require('node:fs'), path=require('node:path');
const {boot}=require('./camera-ui-dom.cjs');
const t=boot(fs.readFileSync(path.join(__dirname,'..','FL-Camera-Review.html'),'utf8'));
const state={ready:true,busy:false,formats:['HEIF','JPEG','RAW'],sizes:[12,48],lenses:[.5,1,2,3],zoom:1,live:true,filteredLive:true,flash:true,autoFlash:true,biasLimits:[-2,2]};
t.report(state);const last=type=>t.messages.filter(m=>m.type===type).at(-1);
t.run('liveShortcut').click();t.open('滤镜');t.brand('sony');
t.run('selector').querySelector('.rail-track').children[1].click();
const mix=t.run('selector').querySelector('input');mix.value='64';mix.dispatch('input');t.close();
let shot=t.capture();assert.equal(shot.look,'FL2');assert.equal(shot.strength,.64);assert.equal(shot.live,true);
const sun=t.run('sun');sun.dispatch('pointerdown',{clientY:90});sun.dispatch('pointermove',{clientY:0});sun.dispatch('pointerup');
assert.equal(last('bias').value,2);shot=t.capture();assert.equal(shot.ev,0);assert.equal(shot.live,true);
console.log('PASS: Live shutter retains chosen look and strength; hardware bias is applied only once');
const stage=t.run('stage');stage.dispatch('pointerdown',{clientX:24,clientY:32});t.fireTimeout(550);stage.dispatch('pointerup');stage.click();
assert.equal(last('focus').lock,true);assert.equal(last('focus').x,24);
const holds=t.messages.filter(m=>m.type==='focus'&&m.lock).length;
stage.dispatch('pointerdown',{clientX:24,clientY:32});stage.dispatch('pointermove',{clientX:60,clientY:90});t.fireTimeout(550);stage.dispatch('pointerup');
assert.equal(t.messages.filter(m=>m.type==='focus'&&m.lock).length,holds);
t.report({...state,focusLocked:true});assert.equal(t.run('lockBadge.hidden'),false);
t.report({...state,focusLocked:false});assert.equal(t.run('lockBadge.hidden'),true);
console.log('PASS: hold sends one lock, a drag cancels it, lock state follows hardware');
t.run('flashTile').click();t.run('selector').querySelectorAll('div button').find(b=>b.textContent==='自动').click();t.close();
t.run('liveShortcut').click();shot=t.capture();assert.equal(shot.live,false);assert.equal(shot.autoFlash,true);
let before=t.messages.filter(m=>m.type==='capture').length;t.host.hardwareShutter();assert.equal(t.messages.filter(m=>m.type==='capture').length,before+1);
t.report({...state,busy:true});t.host.hardwareShutter();assert.equal(t.messages.filter(m=>m.type==='capture').length,before+1);
console.log('PASS: optional automatic flash and hardware shutter use existing capture guards');
